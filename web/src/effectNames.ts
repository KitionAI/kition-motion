/**
 * Effects translated by their id rather than their English name (a name that is another product's
 * stays out of this editor's source): `learnEffectNames` adds their English names, as
 * `effect.list` gives them, to `LEARNED_NAMES_ZH`, which the Chinese phrases read first.
 */
export const EFFECT_IDS_ZH: Record<string, string> = {
  "ec.obsolete.mochashape": "跟踪形状",
}
/** Drop-down options translated by `effect id/parameter id/option value`, for the same reason. */
export const OPTION_IDS_ZH: Record<string, string> = {
  "ec.color.equalize/style/2": "图像编辑器样式",
  "ec.stylize.ccglass/using/1": "合成灯光",
  "ec.stylize.ccplastic/using/1": "合成灯光",
}
export const LEARNED_NAMES_ZH = new Map<string, string>()
type Listed = { id: string; name: string; params?: ReadonlyArray<{ id: string; options?: ReadonlyArray<{ value: number; label: string }> }> }
export function learnEffectNames(list: ReadonlyArray<Listed>) {
  for (const { id, name, params } of list) {
    const zh = EFFECT_IDS_ZH[id]
    if (zh) LEARNED_NAMES_ZH.set(name, zh)
    for (const param of params ?? []) {
      for (const option of param.options ?? []) {
        const label = OPTION_IDS_ZH[`${id}/${param.id}/${option.value}`]
        if (label) LEARNED_NAMES_ZH.set(option.label, label)
      }
    }
  }
}

/** Labels translated by their shape: a cube-map layout keeps its layout's name and ratio. */
export function shapedZh(text: string): string | null {
  const cube = /^Cube-map (.+)$/.exec(text)
  return cube ? `立方体贴图 ${cube[1]}` : null
}

